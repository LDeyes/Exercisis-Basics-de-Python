# Descripció: Mostra un text amb majúscules i minúscules.
# Especificacions d'entrada: Text que es mostra amb majúscules i minúscules.

# Variables
frase = input("Introdueix una frase: ")

majuscules = frase.upper()

minuscules = frase.lower()

# Resultats

print("Frase original:", frase)

print("Frase en majúscules:", majuscules)

print("Frase en minúscules:", minuscules)
