# Descripció: Suma els primers 100 nombres enters
# Especificacions d'entrada: 100 nombres enters

# Variables
suma = 0
comptador = 1

# Programa 
while comptador <= 100:
    suma += comptador
    comptador += 1

print("La suma dels primers 100 nombres enters és: ", suma)
